import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';

// The eight findings (specification §6).
// Frontmatter: label, headline and summary are the WordPress "Headline findings"
// tab label, quote and paragraph. researchHeading, the body and evidence come
// from the latest research report (Report 4, section 3.x).
const stories = defineCollection({
  loader: glob({ pattern: '*.md', base: './src/content/stories' }),
  schema: z.object({
    order: z.number(),
    label: z.string(),
    headline: z.string(),
    summary: z.string(),
    researchHeading: z.string(),
    reportSection: z.string(),
    evidence: z.string(),
    /** Optional qualification shown with the evidence. */
    qualification: z.string().optional(),
  }),
});

// The ideas on What Emerges (specification §7). Generated by scripts/make_ideas.py
// from Report 2: `intro` is the §3 heading, the body is §4 Discussion paragraphs,
// copied exactly. An empty body shows a "to come" placeholder.
const ideas = defineCollection({
  loader: glob({ pattern: '*.md', base: './src/content/ideas' }),
  schema: z.object({
    order: z.number(),
    title: z.string(),
    intro: z.string(),
    introSection: z.string(),
    discussionSections: z.array(z.string()),
    stories: z.array(z.string()),
    /** Participants named in the discussion paragraphs. */
    people: z.array(z.string()),
    related: z.array(z.string()),
  }),
});

export const collections = { stories, ideas };
